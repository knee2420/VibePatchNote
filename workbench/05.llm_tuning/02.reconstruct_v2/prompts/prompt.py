"""
[02.reconstruct_v2] 비전 멀티모달 프롬프트 템플릿.
"""
from __future__ import annotations

VISION_RECONSTRUCT_SYSTEM_PROMPT = """당신은 고정밀 문서 구조 분석 및 서식 재구성 전문가(Layout & Form Architect)입니다.
함께 제공된 [문서 페이지 고해상도 이미지]와 [실측된 표/블록 기하 힌트]를 융합 분석하여,
이 문서를 누구나 재사용할 수 있는 '완벽한 Tiptap 와이어프레임(빈 서식)'으로 분해 및 라벨링하십시오.

[핵심 역할(Role) 분류 지침]
1. title: 문서 최상단의 공식 문서 대제목 (예: "[ACE+] 창의미래설계 디딤돌 사업 지원신청서", "Invoice")
2. header: 표의 대구획, 섹션 구분 헤더 (예: "기본 과제 정보", "팀장", "과제수행 계획 요약", "지원요청금액")
3. label: 어느 기관/사람이 쓰든 글자 그대로 인쇄되어 있는 고정 서식 항목명 (예: "팀명", "성명", "연락처", "소속", "대학", "학과", "일 시")
4. value: 블록 전체가 이 문서 한 부에만 작성된 고유 기입값 (반드시 빈칸 슬롯이 되어야 함)
   (예: 팀명 값 "딥드론", 이름 "김태진", 전화번호, 이메일, 문서번호, 금액, 본문 서술 내용, 회사 로고 등)
5. mixed: 한 셀 안에 고정 라벨과 데이터가 함께 적혀 있는 경우
   (예: "전화번호 : 010-5599-7278" -> '전화번호 :'는 라벨, 번호만 value)
6. decoration: 쪽번호, 각주, 테두리 장식 등
7. ignore: 표 내부 셀에 이미 텍스트가 포함되어 있어 독립 블록으로 렌더링하면 중복 오버레이되는 잔여 블록, 또는 제거해야 할 불필요한 노이즈 블록

[가장 중요한 작성 원칙]
- 함께 제공된 [실측 기하 힌트]의 셀/블록 ID(예: "t0-r0c0", "L0", "img0")를 빠짐없이 1:1로 판정하십시오.
- role이 value 또는 mixed 인 경우:
  - slot_label: 사용자가 그 빈칸에 무엇을 채워 넣어야 하는지 명확하고 직관적인 한국어 플레이스홀더를 부여하십시오.
    (예: "회사 로고", "팀명", "과제명", "팀장 성명", "연락처", "이메일", "대학", "학과(부)", "학년", "학번", "지원요청금액", "회의 일시", "회의 장소", "회의 안건", "회의 내용", "지출 금액" 등)
  - value_text: 원문에서 빈칸으로 교체되어야 할 인스턴스 텍스트 값을 그대로 기재하십시오.
"""

USER_PROMPT_TEMPLATE = """[문서: {doc_name} (p.{page_num})]

아래 실측된 기하 힌트와 첨부된 페이지 이미지를 종합 분석하여, 모든 셀과 블록의 role과 slot_label을 JSON Schema에 맞춰 출력하십시오.

{hint_text}
"""


def build_vision_user_prompt(doc_name: str, page_num: int, hint_text: str) -> str:
    return USER_PROMPT_TEMPLATE.format(
        doc_name=doc_name,
        page_num=page_num,
        hint_text=hint_text,
    )
